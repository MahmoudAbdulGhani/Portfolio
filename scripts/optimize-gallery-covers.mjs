import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Rebuild gallery delivery assets from the reviewed lossless masters, never
// from smaller derivatives or the CMS-owned case-study screenshot collection.
const reviewRoot = 'docs/design/engineered-landscape-covers';
const covers = JSON.parse(await readFile(`${reviewRoot}/cover-treatments.json`, 'utf8'));
const outputRoot = 'public/projects/gallery-covers';
const manifest = {};
await mkdir(outputRoot, { recursive: true });

for (const cover of covers) {
  const master = await readFile(cover.master);
  const metadata = await sharp(master).metadata();
  if (metadata.width !== 1600 || metadata.height !== 1000) {
    throw new Error(`${cover.slug}: expected a 1600×1000 cover master`);
  }
  const base = `/projects/gallery-covers/${cover.slug}`;
  const sources = { width: 1600, height: 1000, placeholder: '', webp: [], avif: [] };
  for (const width of [480, 960, 1600]) {
    const target = path.join(outputRoot, `${cover.slug}-${width}w`);
    await Promise.all([
      sharp(master).resize({ width }).webp({ quality: 92, effort: 6 }).toFile(`${target}.webp`),
      sharp(master).resize({ width }).avif({ quality: 72, effort: 6, chromaSubsampling: '4:4:4' }).toFile(`${target}.avif`),
    ]);
    sources.webp.push(`${base}-${width}w.webp ${width}w`);
    sources.avif.push(`${base}-${width}w.avif ${width}w`);
  }
  await copyFile(`${outputRoot}/${cover.slug}-1600w.webp`, `${outputRoot}/${cover.slug}.webp`);
  manifest[cover.slug] = {
    title: cover.title, alt: cover.alt, src: `${base}.webp`,
    sources: { ...sources, webp: sources.webp.join(', '), avif: sources.avif.join(', ') },
  };
}

await writeFile('src/generated/gallery-covers.ts', `// Generated by npm run images:gallery. Gallery artwork only; case-study media remains CMS-owned.
import type { ProjectImageAsset } from "./project-images";

export type GalleryCover = { title: string; alt: string; src: string; sources: ProjectImageAsset };
export const galleryCovers: Record<string, GalleryCover> = ${JSON.stringify(manifest, null, 2)};
`);
console.log(`Generated ${covers.length} dedicated gallery cover sets.`);
