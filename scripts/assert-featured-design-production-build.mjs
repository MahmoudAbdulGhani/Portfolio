import assert from 'node:assert/strict';
import { readdir, readFile, access } from 'node:fs/promises';
import path from 'node:path';
const root = process.argv[2] ?? 'dist', files = await readdir(path.join(root,'assets'));
const source = (await Promise.all(files.filter(f=>f.endsWith('.js')).map(f=>readFile(path.join(root,'assets',f),'utf8')))).join('\n');
assert(!source.includes('/review/featured/'),'Production excludes Phase 2 route addresses');
assert(!files.some(f=>f.startsWith('FeaturedDesignReview-')),'Production excludes Phase 2 review entry');
await assert.rejects(access(path.join(root,'review/featured-comparison')));
await assert.rejects(access(path.join(root,'review/featured-demo-introductions')));
await assert.rejects(access(path.join(root,'review/featured-adoption')));
assert(source.includes('jobpilot-design-refined'),'Approved JobPilot remains in the normal build');
assert(source.includes('Calculation and interpretation'),'Approved Cedar introduction is available normally');
assert(source.includes('Invitation to call access'),'Approved Lobby introduction is available normally');
const css=(await Promise.all(files.filter(f=>f.endsWith('.css')).map(f=>readFile(path.join(root,'assets',f),'utf8')))).join('\n');
assert(css.includes('demo-introduction')&&css.includes('data-featured-project'),'Approved Phase 2 styles are available normally');
console.log('Normal build adopts approved JobPilot/Cedar/Lobby and excludes review routes, entry and comparison assets.');
