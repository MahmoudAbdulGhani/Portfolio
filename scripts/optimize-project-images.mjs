import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve("public/projects");
const manifestFile = path.resolve("src/generated/project-images.ts");
const widths = [480, 960, 1600];

async function files(directory) {
  return (await Promise.all((await readdir(directory, { withFileTypes: true })).map((entry) => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? files(target) : target;
  }))).flat();
}

const originals = (await files(root)).filter((entry) => entry.toLowerCase().endsWith(".webp") && !/-\d+w\.webp$/i.test(entry));
const manifest = {};
let before = 0;
let after = 0;
for (const file of originals) {
  const source = await readFile(file);
  const pipeline = sharp(source).rotate();
  const metadata = await pipeline.metadata();
  if (!metadata.width || !metadata.height) continue;
  const maxWidth = path.basename(file).toLowerCase() === "cover.webp" ? 1600 : 1920;
  const output = await pipeline.clone()
    .resize({ width: maxWidth, withoutEnlargement: true })
    .webp({ quality: 78, effort: 6, smartSubsample: true })
    .toBuffer();
  before += source.length;
  if (output.length < source.length) {
    await writeFile(file, output);
    after += output.length;
    console.log(`${path.relative(root, file)}: ${metadata.width}x${metadata.height}, ${source.length} -> ${output.length} bytes`);
  } else {
    after += source.length;
  }

  const finalSource = output.length < source.length ? output : source;
  const finalMetadata = await sharp(finalSource).metadata();
  const outputWidths = [...new Set([...widths.filter((width) => width < finalMetadata.width), finalMetadata.width])].sort((a, b) => a - b);
  const extension = path.extname(file);
  const base = file.slice(0, -extension.length);
  const relativeBase = path.relative(path.resolve("public"), base).split(path.sep).join("/");
  const webp = [];
  const avif = [];
  for (const width of outputWidths) {
    const webpFile = `${base}-${width}w.webp`;
    const avifFile = `${base}-${width}w.avif`;
    await Promise.all([
      sharp(finalSource).resize({ width, withoutEnlargement: true }).webp({ quality: 76, effort: 5, smartSubsample: true }).toFile(webpFile),
      sharp(finalSource).resize({ width, withoutEnlargement: true }).avif({ quality: 48, effort: 5 }).toFile(avifFile),
    ]);
    webp.push(`/${relativeBase}-${width}w.webp ${width}w`);
    avif.push(`/${relativeBase}-${width}w.avif ${width}w`);
  }
  const placeholder = await sharp(finalSource).resize({ width: 32 }).webp({ quality: 20, effort: 4 }).toBuffer();
  const publicPath = `/${path.relative(path.resolve("public"), file).split(path.sep).join("/")}`;
  manifest[publicPath] = { width: finalMetadata.width, height: finalMetadata.height, placeholder: `data:image/webp;base64,${placeholder.toString("base64")}`, webp: webp.join(", "), avif: avif.join(", ") };
}

await mkdir(path.dirname(manifestFile), { recursive: true });
await writeFile(manifestFile, `// Generated by npm run images:optimize.\nexport type ProjectImageAsset = { width: number; height: number; placeholder: string; webp: string; avif: string };\nexport const projectImages: Record<string, ProjectImageAsset> = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`Generated ${Object.keys(manifest).length} responsive image sets.`);
console.log(`Project originals: ${before} -> ${after} bytes (${Math.round((1 - after / before) * 100)}% smaller)`);
