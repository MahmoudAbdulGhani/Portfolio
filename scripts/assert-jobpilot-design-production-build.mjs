import assert from 'node:assert/strict';
import { readdir, readFile, access } from 'node:fs/promises';
import path from 'node:path';
const root=process.argv[2]??'dist';
const files=await readdir(path.join(root,'assets'));
const source=(await Promise.all(files.filter(file=>file.endsWith('.js')).map(file=>readFile(path.join(root,'assets',file),'utf8')))).join('\n');
const styles=(await Promise.all(files.filter(file=>file.endsWith('.css')).map(file=>readFile(path.join(root,'assets',file),'utf8')))).join('\n');
assert(!source.includes('/review/jobpilot/'),'Normal Production excludes JobPilot review entry addresses');
assert(!files.some(file=>file.startsWith('JobPilotDesignReview-')),'Normal Production excludes the review entry');
assert(styles.includes('.jobpilot-design-refined'),'Normal Production includes the approved JobPilot styling');
assert(source.includes('Sample data · local demo'),'Normal Production includes the approved concise demonstration');
await assert.rejects(access(path.join(root,'review/jobpilot-comparison')));
await assert.rejects(access(path.join(root,'review/jobpilot-refinement')));
await assert.rejects(access(path.join(root,'review/jobpilot-adoption')));
console.log('Normal compiled build adopts approved JobPilot presentation and excludes review routes, entry and comparison assets.');
