import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const root = 'docs/design/engineered-landscape-portrait/finish';
const treatment = JSON.parse(await readFile(`${root}/processing.json`, 'utf8'));
const master = await readFile(`${root}/portrait-finished-master.png`);
const metadata = await sharp(master).metadata();
if (metadata.width !== 1200 || metadata.height !== 1600 || !metadata.hasAlpha) {
  throw new Error('Expected the registered transparent 1200 × 1600 portrait master');
}
const { crop } = treatment;
const base = '/landscape/portrait-striped-finished';
const variants = [];
await mkdir('public/landscape', { recursive: true });
// The measured 704px export was larger than the sharper native 768px file.
// Keep only useful candidates so srcset cannot choose that dominated export.
for (const width of [320, 384, 480, 640, 768]) {
  if (width > crop.width) throw new Error('Portrait variants must not upscale the native cutout');
  const file = `public${base}-${width}w.webp`;
  const { size, height } = await sharp(master).extract(crop)
    .resize({ width, withoutEnlargement: true })
    .webp({ lossless: true, effort: 6 }).toFile(file);
  variants.push({ width, height, bytes: size, src: `${base}-${width}w.webp` });
}
await copyFile(`public${base}-768w.webp`, `public${base}.webp`);
const portrait = {
  src: `${base}.webp`, width: crop.width, height: crop.height,
  srcSet: variants.map(item => `${item.src} ${item.width}w`).join(', '),
};
await writeFile('src/generated/profile-portrait.ts', `// Generated by npm run images:portrait. Native source detail; no upscaling.
export const profilePortrait = ${JSON.stringify(portrait, null, 2)} as const;
`);
await writeFile(`${root}/delivery.json`, JSON.stringify({ nativeWidth: crop.width, nativeHeight: crop.height, format: 'lossless WebP', variants }, null, 2) + '\n');
console.log(`Generated ${variants.length} lossless portrait variants capped at ${crop.width}px native width.`);
